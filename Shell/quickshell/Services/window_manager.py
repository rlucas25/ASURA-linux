#!/usr/bin/env python3
import sys
import os
import re
import subprocess
import json

ASURA_DIR = os.path.expanduser("~/.config/asura")
HYPR_VARS_FILE = os.path.join(ASURA_DIR, "hypr-vars.lua")
HYPR_USER_FILE = os.path.join(ASURA_DIR, "hypr-user.lua")

def ensure_asura_dir():
    if not os.path.exists(ASURA_DIR):
        os.makedirs(ASURA_DIR, exist_ok=True)

def read_hypr_vars_file() -> dict:
    ensure_asura_dir()
    if not os.path.exists(HYPR_VARS_FILE):
        return {}
    data = {}
    try:
        with open(HYPR_VARS_FILE, "r", encoding="utf-8") as f:
            content = f.read()
        # Parse simple Lua key-value assignments: key = value
        for line in content.splitlines():
            line = line.strip()
            if not line or line.startswith("--") or line.startswith("return") or line.startswith("{") or line.startswith("}"):
                continue
            m = re.match(r'([a-zA-Z0-9_]+)\s*=\s*(.+?)[,;]?$', line)
            if m:
                k = m.group(1).strip()
                v = m.group(2).strip()
                if v == "true":
                    data[k] = True
                elif v == "false":
                    data[k] = False
                elif re.match(r'^-?\d+$', v):
                    data[k] = int(v)
                elif re.match(r'^-?\d+\.\d+$', v):
                    data[k] = float(v)
                elif (v.startswith('"') and v.endswith('"')) or (v.startswith("'") and v.endswith("'")):
                    data[k] = v[1:-1]
                else:
                    data[k] = v
    except Exception as e:
        sys.stderr.write(f"read_hypr_vars_file error: {e}\n")
    return data

def write_hypr_vars_file(data: dict):
    ensure_asura_dir()
    lines = ["-- Generated by Asura Settings", "return {"]
    for k, v in sorted(data.items()):
        if isinstance(v, bool):
            v_str = "true" if v else "false"
        elif isinstance(v, (int, float)):
            v_str = str(v)
        elif isinstance(v, str):
            # If already a Lua expression like "rgba(...)"
            if v.startswith("rgba(") or v.startswith("rgb("):
                v_str = f'"{v}"'
            else:
                v_str = f'"{v}"'
        else:
            v_str = f'"{v}"'
        lines.append(f"    {k} = {v_str},")
    lines.append("}\n")
    content = "\n".join(lines)
    tmp_path = HYPR_VARS_FILE + ".tmp"
    with open(tmp_path, "w", encoding="utf-8") as f:
        f.write(content)
    os.replace(tmp_path, HYPR_VARS_FILE)

def parse_hypr_user_blocks() -> dict:
    blocks = {}
    if not os.path.exists(HYPR_USER_FILE):
        return blocks
    try:
        with open(HYPR_USER_FILE, "r", encoding="utf-8") as f:
            content = f.read()
    except Exception:
        return blocks

    m = re.search(r"hl\.config\s*\(\s*\{", content)
    if not m:
        return blocks
    start = m.end()
    i = start
    n = len(content)
    in_str = None
    escape = False

    while i < n:
        c = content[i]
        if escape:
            escape = False
            i += 1
            continue
        if in_str:
            if c == "\\":
                escape = True
            elif c == in_str:
                in_str = None
            i += 1
            continue
        if c in ("\"", "'"):
            in_str = c
            i += 1
            continue
        if c == "-" and i + 1 < n and content[i + 1] == "-":
            eol = content.find("\n", i)
            if eol == -1:
                break
            i = eol + 1
            continue
        if c == "}" and i + 1 < n and content[i + 1] == ")":
            break

        key_match = re.match(r"([a-zA-Z0-9_]+)\s*=\s*\{", content[i:])
        if key_match:
            key_name = key_match.group(1)
            block_start = i
            line_start = content.rfind("\n", 0, block_start) + 1
            base_indent = block_start - line_start
            brace_pos = i + key_match.end() - 1
            depth = 0
            j = brace_pos
            inner_str = None
            inner_escape = False
            found_end = False

            while j < n:
                jc = content[j]
                if inner_escape:
                    inner_escape = False
                    j += 1
                    continue
                if inner_str:
                    if jc == "\\":
                        inner_escape = True
                    elif jc == inner_str:
                        inner_str = None
                    j += 1
                    continue
                if jc in ("\"", "'"):
                    inner_str = jc
                    j += 1
                    continue
                if jc == "-" and j + 1 < n and content[j + 1] == "-":
                    eol = content.find("\n", j)
                    if eol == -1:
                        break
                    j = eol + 1
                    continue
                if jc == "}" and j + 1 < n and content[j + 1] == ")":
                    break
                if jc == "{":
                    depth += 1
                elif jc == "}":
                    depth -= 1
                    if depth == 0:
                        raw_block = content[block_start:j + 1].strip()
                        lines = raw_block.splitlines()
                        norm_lines = []
                        for l in lines:
                            if l.startswith(" " * base_indent):
                                norm_lines.append(l[base_indent:])
                            else:
                                norm_lines.append(l.lstrip())
                        blocks[key_name] = "\n".join(norm_lines)
                        found_end = True
                        i = j + 1
                        break
                j += 1

            if not found_end:
                raw_block = content[block_start:j].strip()
                lines = raw_block.splitlines()
                norm_lines = []
                for l in lines:
                    if l.startswith(" " * base_indent):
                        norm_lines.append(l[base_indent:])
                    else:
                        norm_lines.append(l.lstrip())
                for _ in range(depth):
                    norm_lines.append("}")
                blocks[key_name] = "\n".join(norm_lines)
                i = j
                continue

        i += 1

    return blocks

def write_hypr_user_blocks(blocks: dict):
    ensure_asura_dir()
    preferred = ["general", "dwindle", "input", "cursor"]
    keys = [k for k in preferred if k in blocks]
    for k in blocks:
        if k not in keys:
            keys.append(k)

    chunks = []
    for k in keys:
        lines = blocks[k].strip().splitlines()
        indented = ["    " + l if l.strip() else "" for l in lines]
        chunks.append("\n".join(indented))

    content = "hl.config({\n" + ",\n".join(chunks) + "\n})\n"
    tmp_path = HYPR_USER_FILE + ".tmp"
    with open(tmp_path, "w", encoding="utf-8") as f:
        f.write(content)
    os.replace(tmp_path, HYPR_USER_FILE)

def write_hypr_user_file(layout: str = "dwindle", smart_split: bool = False):
    layout = layout if layout in ("dwindle", "master", "scrolling") else "dwindle"
    ss_str = "true" if smart_split else "false"
    blocks = parse_hypr_user_blocks()
    blocks["general"] = f"""general = {{
    layout = "{layout}"
}}"""
    blocks["dwindle"] = f"""dwindle = {{
    smart_split = {ss_str}
}}"""
    if "input" not in blocks:
        blocks["input"] = """input = {
    kb_layout = "br,us",
    kb_options = "grp:win_space_toggle",
    numlock_by_default = false,
    repeat_rate = 35,
    repeat_delay = 250,
    sensitivity = 0.0,
    natural_scroll = false,
    left_handed = false,
    scroll_factor = 1.0,
    follow_mouse = 1,
    touchpad = {
        natural_scroll = true,
        disable_while_typing = true,
        tap_to_click = true,
        scroll_factor = 0.5
    }
}"""
    if "cursor" not in blocks:
        blocks["cursor"] = """cursor = {
    no_warps = false
}"""
    write_hypr_user_blocks(blocks)

def get_hypr_option(name: str):
    try:
        res = subprocess.run(["hyprctl", "getoption", name, "-j"], capture_output=True, text=True, timeout=2)
        if res.returncode == 0:
            return json.loads(res.stdout)
    except Exception:
        pass
    return None

def parse_int_or_first(val, default_val=0):
    if val is None:
        return default_val
    if isinstance(val, int):
        return val
    s = str(val).strip()
    parts = s.split()
    if parts:
        try:
            return int(parts[0])
        except ValueError:
            pass
    return default_val

def ensure_hypr_config_compatibility():
    deco_file = os.path.expanduser("~/.config/hypr/hyprland/decoration.lua")
    if os.path.exists(deco_file):
        try:
            with open(deco_file, "r", encoding="utf-8") as f:
                content = f.read()
            if "active_opacity" not in content or "inactive_opacity" not in content:
                new_content = content.replace(
                    "rounding_power = vars.windowRoundingPower,",
                    "rounding_power = vars.windowRoundingPower,\n        active_opacity = vars.activeOpacity or 1.0,\n        inactive_opacity = vars.inactiveOpacity or 1.0,"
                )
                if new_content != content:
                    tmp_path = deco_file + ".tmp"
                    with open(tmp_path, "w", encoding="utf-8") as f:
                        f.write(new_content)
                    os.replace(tmp_path, deco_file)
        except Exception as e:
            sys.stderr.write(f"ensure_hypr_config_compatibility deco error: {e}\n")

    rules_file = os.path.expanduser("~/.config/hypr/hyprland/rules.lua")
    if os.path.exists(rules_file):
        try:
            with open(rules_file, "r", encoding="utf-8") as f:
                rules_content = f.read()

            has_managed_comment = "Opacity is managed dynamically" in rules_content
            uncommented_pattern = r'^[ \t]*hl\.window_rule\(\{\s*match\s*=\s*\{\s*fullscreen\s*=\s*false\s*\}\s*,\s*opacity\s*=\s*vars\.windowOpacity[^\n]*\)'

            if not has_managed_comment and re.search(uncommented_pattern, rules_content, re.MULTILINE):
                replacement = (
                    "-- Opacity is managed dynamically via decoration.active_opacity and decoration.inactive_opacity\n"
                    "-- hl.window_rule({ match = { fullscreen = false }, opacity = vars.windowOpacity .. \" override\" })"
                )
                new_rules_content = re.sub(uncommented_pattern, replacement, rules_content, count=1, flags=re.MULTILINE)
                tmp_path = rules_file + ".tmp"
                with open(tmp_path, "w", encoding="utf-8") as f:
                    f.write(new_rules_content)
                os.replace(tmp_path, rules_file)
            elif has_managed_comment:
                lines = rules_content.splitlines()
                new_lines = []
                in_dupe_block = False
                seen_comment = False
                modified = False

                for line in lines:
                    stripped = line.strip()
                    if "Opacity is managed dynamically via decoration.active_opacity and decoration.inactive_opacity" in stripped:
                        if not seen_comment:
                            new_lines.append("-- Opacity is managed dynamically via decoration.active_opacity and decoration.inactive_opacity")
                            seen_comment = True
                        else:
                            modified = True
                        in_dupe_block = True
                        continue
                    if in_dupe_block:
                        if stripped == "":
                            modified = True
                            continue
                        if "hl.window_rule({ match = { fullscreen = false }, opacity = vars.windowOpacity" in stripped:
                            new_lines.append('-- hl.window_rule({ match = { fullscreen = false }, opacity = vars.windowOpacity .. " override" })')
                            in_dupe_block = False
                            continue
                        in_dupe_block = False
                    new_lines.append(line)

                if modified:
                    cleaned_content = "\n".join(new_lines) + "\n"
                    tmp_path = rules_file + ".tmp"
                    with open(tmp_path, "w", encoding="utf-8") as f:
                        f.write(cleaned_content)
                    os.replace(tmp_path, rules_file)
        except Exception as e:
            sys.stderr.write(f"ensure_hypr_config_compatibility rules error: {e}\n")

def get_current_settings():
    ensure_hypr_config_compatibility()
    hypr_vars = read_hypr_vars_file()

    # Query active values from hyprctl for real-time accuracy
    g_in_opt = get_hypr_option("general:gaps_in")
    g_out_opt = get_hypr_option("general:gaps_out")
    border_opt = get_hypr_option("general:border_size")
    layout_opt = get_hypr_option("general:layout")
    rnd_opt = get_hypr_option("decoration:rounding")
    rnd_pwr_opt = get_hypr_option("decoration:rounding_power")
    sh_en_opt = get_hypr_option("decoration:shadow:enabled")
    sh_rng_opt = get_hypr_option("decoration:shadow:range")
    sh_pwr_opt = get_hypr_option("decoration:shadow:render_power")
    act_op_opt = get_hypr_option("decoration:active_opacity")
    inact_op_opt = get_hypr_option("decoration:inactive_opacity")
    ss_opt = get_hypr_option("dwindle:smart_split")

    gaps_in = hypr_vars.get("windowGapsIn", parse_int_or_first(g_in_opt.get("int") or g_in_opt.get("css"), 4) if g_in_opt else 4)
    gaps_out = hypr_vars.get("windowGapsOut", parse_int_or_first(g_out_opt.get("int") or g_out_opt.get("css"), 8) if g_out_opt else 8)
    single_gaps_out = hypr_vars.get("singleWindowGapsOut", gaps_out)
    border_size = hypr_vars.get("windowBorderSize", border_opt.get("int", 2) if border_opt else 2)
    rounding = hypr_vars.get("windowRounding", rnd_opt.get("int", 15) if rnd_opt else 15)
    rounding_power = hypr_vars.get("windowRoundingPower", rnd_pwr_opt.get("int", 2) if rnd_pwr_opt else 2)
    shadow_enabled = hypr_vars.get("shadowEnabled", sh_en_opt.get("bool", True) if sh_en_opt else True)
    shadow_range = hypr_vars.get("shadowRange", sh_rng_opt.get("int", 15) if sh_rng_opt else 15)
    shadow_render_power = hypr_vars.get("shadowRenderPower", sh_pwr_opt.get("int", 4) if sh_pwr_opt else 4)
    active_opacity = hypr_vars.get("activeOpacity", act_op_opt.get("float", 1.0) if act_op_opt else 1.0)
    inactive_opacity = hypr_vars.get("inactiveOpacity", inact_op_opt.get("float", 1.0) if inact_op_opt else 1.0)
    layout = hypr_vars.get("layout", layout_opt.get("str", "dwindle") if layout_opt else "dwindle")
    smart_split = hypr_vars.get("smartSplit", ss_opt.get("bool", False) if ss_opt else False)

    return {
        "windowGapsIn": gaps_in,
        "windowGapsOut": gaps_out,
        "singleWindowGapsOut": single_gaps_out,
        "windowBorderSize": border_size,
        "windowRounding": rounding,
        "windowRoundingPower": rounding_power,
        "shadowEnabled": shadow_enabled,
        "shadowRange": shadow_range,
        "shadowRenderPower": shadow_render_power,
        "activeOpacity": round(float(active_opacity), 2),
        "inactiveOpacity": round(float(inactive_opacity), 2),
        "layout": layout,
        "smartSplit": smart_split
    }

def apply_settings(payload: dict) -> bool:
    ensure_hypr_config_compatibility()
    cur = get_current_settings()
    orig_layout = cur.get("layout")
    orig_ss = cur.get("smartSplit")
    cur.update(payload)

    # Normalize values
    gaps_in = max(0, min(64, int(cur.get("windowGapsIn", 4))))
    gaps_out = max(0, min(80, int(cur.get("windowGapsOut", 8))))
    single_gaps_out = max(0, min(80, int(cur.get("singleWindowGapsOut", gaps_out))))
    border_size = max(0, min(16, int(cur.get("windowBorderSize", 2))))
    rounding = max(0, min(40, int(cur.get("windowRounding", 15))))
    rounding_power = max(1, min(4, int(cur.get("windowRoundingPower", 2))))
    shadow_en = bool(cur.get("shadowEnabled", True))
    shadow_en_str = "true" if shadow_en else "false"
    shadow_range = max(1, min(80, int(cur.get("shadowRange", 15))))
    shadow_power = max(1, min(5, int(cur.get("shadowRenderPower", 4))))
    act_op = max(0.2, min(1.0, float(cur.get("activeOpacity", 1.0))))
    inact_op = max(0.2, min(1.0, float(cur.get("inactiveOpacity", 1.0))))
    layout = str(cur.get("layout", "dwindle")).strip().lower()
    if layout not in ("dwindle", "master", "scrolling"):
        layout = "dwindle"
    smart_split = bool(cur.get("smartSplit", False))
    ss_str = "true" if smart_split else "false"

    # Live update via hyprctl eval (zero latency)
    lua_code = f"""
hl.config({{
    general = {{
        gaps_in = {gaps_in},
        gaps_out = {gaps_out},
        border_size = {border_size},
        layout = "{layout}"
    }},
    decoration = {{
        rounding = {rounding},
        rounding_power = {rounding_power},
        active_opacity = {act_op},
        inactive_opacity = {inact_op},
        shadow = {{
            enabled = {shadow_en_str},
            range = {shadow_range},
            render_power = {shadow_power}
        }}
    }},
    dwindle = {{
        smart_split = {ss_str}
    }}
}})
hl.workspace_rule({{ workspace = "w[tv1]s[false]", gaps_out = {single_gaps_out} }})
hl.workspace_rule({{ workspace = "f[1]s[false]", gaps_out = {single_gaps_out} }})
return "ok"
"""
    try:
        res = subprocess.run(["hyprctl", "eval", lua_code], capture_output=True, text=True, timeout=3)
        ok = (res.returncode == 0)
    except Exception as e:
        sys.stderr.write(f"apply_settings hyprctl error: {e}\n")
        ok = False

    # Persist cleanly to user overlay in ~/.config/asura/hypr-vars.lua
    existing_vars = read_hypr_vars_file()
    existing_vars["windowGapsIn"] = gaps_in
    existing_vars["windowGapsOut"] = gaps_out
    existing_vars["singleWindowGapsOut"] = single_gaps_out
    existing_vars["windowBorderSize"] = border_size
    existing_vars["windowRounding"] = rounding
    existing_vars["windowRoundingPower"] = rounding_power
    existing_vars["shadowEnabled"] = shadow_en
    existing_vars["shadowRange"] = shadow_range
    existing_vars["shadowRenderPower"] = shadow_power
    existing_vars["activeOpacity"] = round(act_op, 2)
    existing_vars["inactiveOpacity"] = round(inact_op, 2)
    existing_vars["windowOpacity"] = round(act_op, 2)
    existing_vars["layout"] = layout
    existing_vars["smartSplit"] = smart_split

    write_hypr_vars_file(existing_vars)
    if orig_layout != layout or orig_ss != smart_split:
        write_hypr_user_file(layout=layout, smart_split=smart_split)

    return ok

def main():
    if len(sys.argv) < 2:
        print(json.dumps({"error": "Missing command"}))
        sys.exit(1)

    cmd = sys.argv[1]
    if cmd == "get":
        cur = get_current_settings()
        print(json.dumps(cur))
    elif cmd == "apply":
        if len(sys.argv) < 3:
            print(json.dumps({"error": "Missing payload JSON"}))
            sys.exit(1)
        try:
            payload = json.loads(sys.argv[2])
            ok = apply_settings(payload)
            print(json.dumps({"success": ok, "settings": payload}))
        except Exception as e:
            print(json.dumps({"error": str(e)}))
            sys.exit(1)
    else:
        print(json.dumps({"error": f"Unknown command {cmd}"}))
        sys.exit(1)

if __name__ == "__main__":
    main()
